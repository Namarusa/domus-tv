#!/usr/bin/env python3
"""Build the Domus web client.

Wraps the Freebox app's shared JS (tv/js/model.js, mdi.js, theme.js) into browser
namespaces (Model, Mdi, Theme), copies the icon font, and assembles:
  web/dist/www      plain web app (open index.html in a browser to test)
  web/dist/webos    LG webOS app folder (+ .ipk if ares-package is installed)

Usage: python3 web/tools/build.py [--url http://192.168.1.10:8123] [--ipk]
"""
import argparse, json, os, re, shutil, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TV = os.path.join(ROOT, "tv")
WEB = os.path.join(ROOT, "web")
DIST = os.path.join(WEB, "dist")


def wrap(src_path, ns):
    src = open(src_path, encoding="utf-8").read().replace(".pragma library", "")
    names = re.findall(r"^(?:function\s+([A-Za-z_$][\w$]*)|var\s+([A-Za-z_$][\w$]*))", src, re.M)
    names = sorted({a or b for a, b in names})
    exports = ", ".join('"%s": %s' % (n, n) for n in names)
    return "var %s = (function () {\n%s\nreturn { %s };\n})();\n" % (ns, src, exports)


def tv_version():
    m = re.search(r'VERSION\s*=\s*"([^"]+)"', open(os.path.join(TV, "js", "config.js")).read())
    return m.group(1)


def build_www(url):
    out = os.path.join(DIST, "www")
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(os.path.join(WEB, "src"), out)
    gen = os.path.join(out, "js", "shared.js")
    with open(gen, "w", encoding="utf-8") as f:
        f.write("// Generated by web/tools/build.py from tv/js. Do not edit.\n")
        f.write(wrap(os.path.join(TV, "js", "theme.js"), "Theme"))
        f.write(wrap(os.path.join(TV, "js", "mdi.js"), "Mdi"))
        f.write(wrap(os.path.join(TV, "js", "model.js"), "Model"))
    os.makedirs(os.path.join(out, "fonts"), exist_ok=True)
    for f in ("materialdesignicons-webfont.ttf", "MDI-LICENSE.txt"):
        shutil.copy(os.path.join(TV, "fonts", f), os.path.join(out, "fonts", f))
    cfg = os.path.join(out, "js", "config.js")
    s = open(cfg, encoding="utf-8").read()
    s = s.replace("__VERSION__", tv_version())
    if url:
        s = re.sub(r'DEFAULT_URL: "[^"]*"', 'DEFAULT_URL: "%s"' % url, s)
    open(cfg, "w", encoding="utf-8").write(s)
    return out


def build_webos(www, ipk):
    out = os.path.join(DIST, "webos")
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(www, out)
    plat = os.path.join(WEB, "platforms", "webos")
    info = json.load(open(os.path.join(plat, "appinfo.json")))
    info["version"] = tv_version()
    json.dump(info, open(os.path.join(out, "appinfo.json"), "w"), indent=2)
    for f in os.listdir(plat):
        if f.endswith(".png"):
            shutil.copy(os.path.join(plat, f), os.path.join(out, f))
    if ipk:
        subprocess.check_call(["ares-package", out, "-o", DIST, "--no-minify"])
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="")
    ap.add_argument("--ipk", action="store_true")
    a = ap.parse_args()
    www = build_www(a.url)
    print("www  ->", www)
    print("webos ->", build_webos(www, a.ipk))
